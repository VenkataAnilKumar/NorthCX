"""Writes (or checks) the generated route reference at the end of docs/04-integrations/NorthCX_API-Design.md.

The table comes from the server's permission table, so the documentation cannot silently drift from the code:
    python scripts/gen_route_reference.py            # rewrite the generated block
    python scripts/gen_route_reference.py --check    # exit 1 if the document is out of date
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "04-integrations" / "NorthCX_API-Design.md"
START, END = "<!-- routes:start (generated by scripts/gen_route_reference.py) -->", "<!-- routes:end -->"


def pretty(regex: str) -> str:
    p = regex.replace("[^/]+", "{id}").replace(".+", "{path}")
    p = re.sub(r"\((\w+)\|(\w+)\|(\w+)\)", r"{\1|\2|\3}", p)
    return p.replace("/v1", "", 1)


def render() -> str:
    sys.path.insert(0, str(ROOT / "src" / "backend"))
    from northcx.server import ROUTE_PERMISSIONS
    rows = sorted({(pretty(path), method, perm) for method, path, perm in ROUTE_PERMISSIONS}, key=lambda r: (r[0], r[1]))
    lines = [START, "", f"Every route that needs a key ({len(rows)}), with the permission it requires. Generated from the server's permission table; a test fails if this list and the code disagree.", "",
             "| Method | Path (under `/v1`) | Permission |", "|---|---|---|"]
    lines += [f"| {m} | `{p}` | `{perm}` |" for p, m, perm in rows]
    lines += ["", END]
    return "\n".join(lines)


def current() -> str:
    t = DOC.read_text()
    a, b = t.find(START), t.find(END)
    return t[a:b + len(END)] if a != -1 and b != -1 else ""


def main() -> int:
    want = render()
    if "--check" in sys.argv:
        if current() != want:
            print("The route reference in NorthCX_API-Design.md is out of date: run python scripts/gen_route_reference.py")
            return 1
        return 0
    t = DOC.read_text()
    if START in t:
        a, b = t.find(START), t.find(END)
        t = t[:a] + want + t[b + len(END):]
    else:
        t = t.rstrip("\n") + "\n\n## Route reference\n\n" + want + "\n"
    DOC.write_text(t)
    print("updated", DOC.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
