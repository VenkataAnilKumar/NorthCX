#!/usr/bin/env bash
# Regenerate the backend's hash-pinned lock files from src/backend/pyproject.toml.
#   requirements.lock      runtime dependencies (what the container image installs)
#   requirements-dev.lock  runtime plus the test tools (what CI installs)
# Needs `uv` (https://docs.astral.sh/uv/). Run it whenever pyproject.toml's dependencies change, or to take newer
# versions (add --upgrade). A test fails when a lock no longer matches pyproject.toml.
set -euo pipefail
cd "$(dirname "$0")/../src/backend"
FP="$(python3 ../../scripts/lock_hash.py)"
common=(--generate-hashes --universal --python-version 3.12 --no-header --quiet "$@")
write() {  # write <out> <extra args...>
  local out="$1"; shift
  local tmp; tmp="$(mktemp)"
  uv pip compile pyproject.toml "${common[@]}" "$@" -o "$tmp"
  { echo "# Generated by scripts/lock.sh; do not edit. Regenerate after changing pyproject.toml."
    echo "# pyproject-fingerprint: $FP"
    cat "$tmp"; } > "$out"
  rm -f "$tmp"
}
write requirements.lock
write requirements-dev.lock --extra dev
echo "Wrote requirements.lock and requirements-dev.lock (fingerprint $FP)"
